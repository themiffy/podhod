def build_stats_messages(report: str, history: str, sportsmen: Optional[str],
                         period: int) -> list[dict[str, str]]:
    task = (
        f'Оцени, как спортсмен {sportsmen} двигается. Ограничься самым важным.'
        if sportsmen else
        'Оцени, как все спортсмены двигаются. Сравни участников и выяви '
        'связи, если они подтверждаются данными. Уложись в несколько абзацев.'
    )
    return [
        {'role': 'system', 'content': CORE_CHARACTER},
        {'role': 'user', 'content': (
            f'{task}\nОтчётный период: {period} дней.\n\n'
            f'Подсчитанная статистика:\n{report}\n\n'
            f'История подходов (от новых к старым):\n{history or "Подходов нет."}'
        )},
    ]
